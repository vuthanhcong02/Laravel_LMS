    /**
     * Hiển thị trang Chiết tự Chữ Hán theo cấu trúc Bộ thủ & Bảng Bộ thủ
     */
    public function index(Request $request): View
    {
        $radicalGroups = $this->getRadicalGroups();
        $demoRadicals = $this->getDemoRadicals();

        return view('hanzi.index', compact('radicalGroups', 'demoRadicals'));
    }

    /**
     * API tra cứu chữ Hán và Bộ thủ nhanh
     */
    public function search(Request $request): JsonResponse
    {
        $keyword = trim($request->input('q', ''));
        $allCharacters = $this->getAllCharacters();

        if (empty($keyword)) {
            return response()->json(array_values($allCharacters));
        }

        $filtered = array_filter($allCharacters, function ($item) use ($keyword) {
            return mb_stripos($item['character'], $keyword) !== false
                || mb_stripos($item['pinyin'], $keyword) !== false
                || mb_stripos($item['sino_vietnamese'], $keyword) !== false
                || mb_stripos($item['meaning'], $keyword) !== false
                || mb_stripos($item['radical_name'] ?? '', $keyword) !== false;
        });

        return response()->json(array_values($filtered));
    }

    /**
     * Danh sách chữ Hán dạng phẳng hỗ trợ tra cứu và kiểm thử tương thích ngược
     */
    public function getAllCharacters(): array
    {
        $flatList = [];
        $groups = $this->getRadicalGroups();

        foreach ($groups as $group) {
            foreach ($group['characters'] as $key => $char) {
                $char['radical_id'] = $group['id'];
                $char['radical_name'] = $group['name'];
                $char['radical_symbol'] = $group['radical'];
                $flatList[$key] = $char;
            }
        }

        return $flatList;
    }

